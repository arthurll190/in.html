create table public.ranking_tiro (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) > 0 and char_length(nome) <= 20),
  pontos integer not null check (pontos >= 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.ranking_tiro enable row level security;

create policy "Permitir leitura publica do ranking"
on public.ranking_tiro for select
to anon
using (true);

create policy "Permitir inserir pontuacao valida"
on public.ranking_tiro for insert
to anon
with check (char_length(trim(nome)) > 0 and char_length(nome) <= 20 and pontos >= 0);
